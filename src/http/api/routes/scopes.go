func ScopeContract(route APIRoute, op Operation) ([]string, bool) {
	if route.Public {
		return nil, true
	}
	path := route.Path
	if op.Suffix != "" {
		path = strings.TrimSuffix(path, "/") + "/" + op.Suffix
	}
	v, ok := scopeContracts[op.Method+" "+path]
	return append([]string(nil), v...), ok
}
